#!/usr/bin/env python3
"""Writes android/app/src/main/res/values-<locale>/strings.xml from the app
catalogs, so the Android notification speaks the same language as the app.
Run after translate.mjs: python3 tool/i18n/android_strings.py"""
import json, pathlib, re
from xml.sax.saxutils import escape

ROOT = pathlib.Path(__file__).resolve().parents[2]
RES = ROOT / 'android/app/src/main/res'
# Catalog code -> Android resource folders (BCP 47 form plus the plain language).
FOLDERS = {'es': ['values-es'], 'zh-Hans': ['values-b+zh+Hans', 'values-zh'], 'de': ['values-de'], 'fr': ['values-fr'],
           'ja': ['values-ja'], 'ko': ['values-ko'], 'pt-BR': ['values-pt-rBR', 'values-pt']}
base = (RES / 'values/strings.xml').read_text()
entries = re.findall(r'<string name="([^"]+)">(.*?)</string>', base)
for code, folders in FOLDERS.items():
    cat = json.loads((ROOT / f'assets/i18n/{code}.json').read_text())
    body = ''.join(f'    <string name="{n}">{escape(cat.get(v, v)).replace(chr(39), chr(92) + chr(39))}</string>\n' for n, v in entries)
    xml = f'<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tool/i18n/android_strings.py from assets/i18n/{code}.json. -->\n<resources>\n{body}</resources>\n'
    for f in folders:
        (RES / f).mkdir(exist_ok=True)
        (RES / f / 'strings.xml').write_text(xml)
    print(code, len(entries))
